from typing import Any

from src.app.common.ai.abcs import IModelConfig
from src.app.common.ai.behavior import AIBehavior


class AIModelConfig(IModelConfig[AIBehavior]):
    """
    Пресеты конфигов для поведения ИИ.

    Этот класс инкапсулирует технические настройки, управляющие случайностью,
    лимитами токенов, объемом памяти (контекста) и штрафами за повторения слов
    для моделей семейства Llama 3 в игровом ядре `7dtd_ai_core`.

    ``temperature``:
        Температура (хаос и творчество). Управляет случайностью выбора слов.
        Значения близкие к 0.0 делают модель строго предсказуемой и точной
        (идеально для JSON).
        Значения близкие к 1.0 повышают креативность, но увеличивают риск
        галлюцинаций.
        Диапазон: [0.0, 1.0].
    ``top_p``:
        Ядерное сэмплирование (Nucleus sampling). Ограничивает размер пула слов,
        из которых модель выбирает ответ. Значение 0.9 означает, что модель
        отсортирует все слова по вероятности и отбросит 10% самого маловероятного
        «мусора», выбирая только из топ-90%.
        Диапазон: (0.0, 1.0].
    ``num_predict``:
        Ограничитель длины ответа (max_tokens). Максимальное количество
        токенов, которое модель может сгенерировать за один запрос.
        Защищает сервер от бесконечных циклов генерации и экономит время видеокарты.
    ``num_ctx``:
        Количество токенов, использует память в видеокарте.
        Задает максимальный объем текста (системный промт +
        история из БД + текущий вопрос), который модель способна удержать в голове
        за раз. Если этот лимит превышен, модель начнет незаметно забывать самые
        старые сообщения.
    ``repeat_penalty``:
        Штраф за тавтологию. Коэффициент, который наказывает модель за
        повторение одних и тех же слов в тексте. Значения больше 1.0 заставляют
        ИИ искать синонимы и строить более разнообразные предложения.
        Диапазон: [0.0, 2.0].
    """

    _PRESETS: dict[str, dict[str, Any]] = {
        AIBehavior.MODERATOR: {
            "temperature": 0.1,
            "top_p": 0.2,
            "num_predict": 512,
        },
        AIBehavior.ASSISTANT: {
            "temperature": 0.2,
            "top_p": 0.7,
            "num_predict": 300,
        },
        AIBehavior.STORYTELLER: {
            "temperature": 0.45,
            "top_p": 0.85,
            "repeat_penalty": 1.15,
            "num_predict": 400,
        },
        AIBehavior.ENTERTAINER: {
            "temperature": 0.75,
            "top_p": 0.9,
            "repeat_penalty": 1.1,
            "num_predict": 150,
        },
        AIBehavior.TOOL_ROUTER: {
            "temperature": 0.0,
            "top_p": 0.0,
            "repeat_penalty": 1.0,
            "num_predict": 64,
        },
    }

    @classmethod
    def get(cls, behavior: AIBehavior) -> dict[str, dict[str, int | float]]:
        return cls._PRESETS[behavior]
